package cpw.mods.fml.client;

import java.util.List;

import net.minecraft.client.gui.FontRenderer;
import net.minecraft.client.renderer.Tessellator;

import cpw.mods.fml.common.ModContainer;

/**
 * The list on the left of the mod list: each mod with its logo, name, badges and the start of its description.
 *
 * @author cpw
 *
 */
public class GuiSlotSpoonModList extends GuiScrollingList
{
    private static final int ICON_INSET = 2;
    private static final int DESCRIPTION_LINES = 2;

    private GuiSpoonModList parent;
    private List<ModContainer> mods;

    public GuiSlotSpoonModList(GuiSpoonModList parent, List<ModContainer> mods, int listWidth, int top, int bottom, int left)
    {
        super(parent.getMinecraftInstance(), listWidth, parent.height, top, bottom, left, GuiSpoonModList.ENTRY_HEIGHT);
        this.parent=parent;
        this.mods=mods;
    }

    boolean contains(int x, int y)
    {
        return x >= this.left && x < this.left + this.listWidth && y >= this.top && y < this.bottom;
    }

    @Override
    protected int getSize()
    {
        return mods.size();
    }

    @Override
    protected void elementClicked(int index, boolean doubleClick)
    {
        this.parent.selectModIndex(index);
    }

    @Override
    protected boolean isSelected(int index)
    {
        return this.parent.modIndexSelected(index);
    }

    @Override
    protected void drawBackground()
    {
        // GuiSpoonModList draws the screen background before its lists
    }

    @Override
    protected int getContentHeight()
    {
        return this.getSize() * GuiSpoonModList.ENTRY_HEIGHT + 1;
    }

    @SuppressWarnings("unchecked")
    @Override
    protected void drawSlot(int index, int right, int top, int height, Tessellator tess)
    {
        ModContainer mod = mods.get(index);
        FontRenderer font = this.parent.getFontRenderer();
        int iconLeft = this.left + ICON_INSET;
        this.parent.drawModIcon(mod, iconLeft, top);

        int childCount = mod.getMetadata() != null ? mod.getMetadata().childMods.size() : 0;
        if (childCount > 0)
        {
            String count = String.valueOf(childCount);
            font.drawStringWithShadow(count, iconLeft + GuiSpoonModList.ICON_SIZE - font.getStringWidth(count), top + GuiSpoonModList.ICON_SIZE - font.FONT_HEIGHT + 1, GuiSpoonModList.COLOR_TEXT);
        }

        int textLeft = iconLeft + GuiSpoonModList.ICON_SIZE + GuiSpoonModList.GAP;
        int textWidth = right - textLeft - ICON_INSET;
        this.parent.drawNameAndBadges(mod, textLeft, top, textWidth, false);

        String description = mod.getMetadata() != null && !mod.getMetadata().autogenerated ? mod.getMetadata().description : "";
        List<String> lines = font.listFormattedStringToWidth(description == null ? "" : description, textWidth);
        for (int i = 0; i < DESCRIPTION_LINES && i < lines.size(); i++)
        {
            String line = lines.get(i);
            if (i == DESCRIPTION_LINES - 1 && lines.size() > DESCRIPTION_LINES)
            {
                line = line + "...";
            }
            this.parent.drawTrimmed(line, textLeft, top + 1 + GuiSpoonModList.LINE_HEIGHT * (i + 1), textWidth, GuiSpoonModList.COLOR_SECONDARY, false);
        }
    }

}
